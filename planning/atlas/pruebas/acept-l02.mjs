import { chromium } from 'playwright';
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH });
const p = await b.newPage({ viewport: { width: 1920, height: 1080 } });
const errs = []; p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
const U = 'http://localhost:8000/atlas/completo/';
const ir = async (id) => { await p.goto(`${U}?r=${Math.random()}#${id}`); await p.waitForTimeout(1300); };
const txt = (sel) => p.$eval(`section.is-active ${sel}`, (e) => e.textContent.trim());
const ok = (n, c, x = '') => console.log(`${c ? '✓' : '✗'} ${n}${x ? ' · ' + x : ''}`);
const huella = () => p.$eval('section.is-active [data-role="puntos"] canvas', (c) => { const d = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let h = 0; for (let i = 0; i < d.length; i += 97) h = (h * 31 + d[i]) >>> 0; return h; });
await ir('l02-api-rng-noise'); const h7 = await huella();
await p.click('section.is-active [data-semilla="42"]'); await p.waitForTimeout(300); const h42 = await huella();
ok('semilla 42 cambia el dibujo', h7 !== h42, await txt('[data-role="estado"]'));
await p.click('section.is-active [data-semilla="7"]'); await p.waitForTimeout(300);
ok('semilla 7 repite exactamente', (await huella()) === h7);
await ir('l02-motor-gl'); ok('gl: contexto', /WebGL/.test(await txt('[data-role="estado"]')), await txt('[data-role="estado"]'));
await ir('l02-motor-color-contraste');
const c = await p.evaluate(() => Motor.color.contrast(getComputedStyle(document.querySelector('section.is-active')).getPropertyValue('--fg').trim(), getComputedStyle(document.querySelector('section.is-active')).getPropertyValue('--bg').trim()));
ok('contraste fg/bg coincide con la API', (await txt('[data-role="demo"]')).includes(c.toFixed(2).replace('.', ',')), c.toFixed(2));
await ir('l02-api-dom'); const t = await txt('[data-role="codigo"]'); ok('api.qa cuenta solo esta diapositiva', /length\s+4\b/.test(t) || /length\s+\d+/.test(t), t.split('\n')[0]);
await ir('l02-api-tiempo'); await p.waitForTimeout(200); const x1 = await p.$eval('section.is-active circle', (e) => +e.getAttribute('cx')); await p.waitForTimeout(500);
const x2 = await p.$eval('section.is-active circle', (e) => +e.getAttribute('cx')); ok('raf anima', x1 !== x2);
await p.keyboard.press('ArrowRight'); await p.waitForTimeout(600);
const x3 = await p.$eval('#l02-api-tiempo circle', (e) => +e.getAttribute('cx')); await p.waitForTimeout(600);
ok('raf se para al salir', x3 === (await p.$eval('#l02-api-tiempo circle', (e) => +e.getAttribute('cx'))));
ok('sin errores', errs.length === 0, errs.join(' | '));
await b.close();
